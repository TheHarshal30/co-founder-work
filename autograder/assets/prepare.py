"""Prepare missing test assets for a rules file, then hand them to the grader.

    rules.json (+ statement, examples, any instructor files)
          |
          v  1. inventory   which assets does each configured analyzer need,
          |                 and which of them are missing on disk?
          |                 (nothing missing -> no overlay: the existing
          |                  explicit-assets workflow runs unchanged)
          v  2. cache       key = hash(rules, statement, instructor assets,
          |                 model, settings, generator version, compiler);
          |                 a validated bundle in SQLite with that key is reused
          v  3. infer       a problem brief from the title, statement, limits,
          |                 sample and example outputs (no ``asset_generation``
          |                 block is required; it only overrides defaults)
          v  4. generate    input spec -> generator, boundary + LLM corner
          |                 cases, independent oracle programs, known solutions
          v  5. validate    every candidate is checked independently; rejected
          |                 ones are recorded with the reason, never used
          v  6. decide      per metric: ready | prepared | partial | not_performed
          v  7. store       SQLite rows (+ audit trail), then the files under
                            <cache>/generated/<problem>/<generation_id>/,
                            separate from the instructor's files:

        manifest.json              what was decided, per metric
        validation/report.json     every asset: status, origin, reason
        spec/input_spec.json       the validated input format
        generators/gen.py          deterministic generator (fixed template)
        tests/<metric>/*.in|.out   correctness tests
        edge_cases/<metric>.json   corner cases with their expected outputs
        inputs/replay_inputs.json  inputs replayed under the sanitizers
        oracles/<style>.c          every oracle candidate, accepted or not
        reference/reference.c      the generated reference (full consensus only)
        known/*.c                  LLM solutions for the originality check

The result is an ``AssetOverlay`` for ``load_rules``: the rules file stays the
authority on what is graded and how much it weighs; the overlay only says where
generated assets live and which probes could not be checked.

Generated assets do not depend on the submission on purpose: every student is
graded against the same test set, and a batch prepares once. (The one
exception, the input-format hint when the instructor gave no input at all, is
part of the cache key and reported.)
"""

