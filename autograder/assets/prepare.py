"""Prepare missing test assets for a rules file, then hand them to the grader.

    rules.json (+ statement, if any)            submission.c is NOT an input here
          |
          v  1. inventory   which assets does each configured analyzer need,
          |                 and which of them are missing on disk?
          |                 (nothing missing -> no overlay: the existing
          |                  explicit-assets workflow runs unchanged)
          v  2. cache       key = hash(rules, statement, instructor assets,
          |                 model, settings, generator version, compiler);
          |                 a validated bundle in SQLite with that key is reused
          v  3. generate    input spec -> generator, boundary + LLM corner
          |                 cases, (opt-in) LLM oracle, known LLM solutions
          v  4. validate    every candidate is checked independently; rejected
          |                 ones are recorded with the reason, never used
          v  5. decide      per metric: ready | prepared | partial | not_performed
          v  6. store       SQLite rows (+ audit trail), then materialise the
                            validated files into <cache>/assets/<key>/, a folder
                            separate from the instructor's files

The result is an ``AssetOverlay`` for ``load_rules``: the rules file stays the
authority on what is graded and how much it weighs; the overlay only says where
generated assets live and which probes could not be checked.

Generated assets do not depend on the submission on purpose: every student is
graded against the same test set, and a batch prepares once.
"""

