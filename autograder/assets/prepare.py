def safe_name(text: str, fallback: str = "x") -> str:
    """A path component that is valid on Linux, macOS and Windows."""
    clean = re.sub(r"[^A-Za-z0-9_.-]+", "_", str(text)).strip("._")[:60]
    return clean or fallback


# -- configuration (the optional "asset_generation" block of the rules) ----------
@dataclass
class Config:
    provider: str = "ollama"
    model: str = "qwen2.5:7b"
    seed: int = 42
    max_retries: int = 3
    oracle: str = "auto"  # auto (= llm_consensus) | llm_consensus | none
    oracle_candidates: int = 3
    min_examples_for_oracle: int = 0
    max_case_families: int = 6
    known_solutions: int = 3
    max_input_bytes: int = 50_000
    oracle_max_input_bytes: int = 4_000
    description: str = ""
    input_spec: Optional[dict] = None
    examples: List[Tuple[str, str]] = field(default_factory=list)

    @classmethod
    def from_rules(cls, raw: Dict[str, Any], overrides: Optional[Dict[str, str]] = None) -> Tuple["Config", List[str]]:
        """Defaults, then the rules' ``asset_generation`` block (optional), then
        the operator's provider/model choice (CLI flags, the UI, or the
        AUTOGRADER_LLM_PROVIDER / AUTOGRADER_LLM_MODEL environment)."""
        block = raw.get("asset_generation", {})
        if not isinstance(block, dict):
            return cls(), ["'asset_generation' must be an object"]
        c, problems = cls(), []

        def get(key, typ, check, msg):
            if key not in block:
                return
            v = block[key]
            if not isinstance(v, typ) or isinstance(v, bool) and typ is not bool or not check(v):
                problems.append(f"asset_generation.{key}: {msg}")
            else:
                setattr(c, key, v)

        get("provider", str, lambda v: v in PROVIDERS, f"must be one of {', '.join(PROVIDERS)}")
        get("model", str, bool, "must be a non-empty string")
        get("seed", int, lambda v: True, "must be an integer")
        get("max_retries", int, lambda v: 1 <= v <= 10, "must be 1..10")
        get("oracle", str, lambda v: v in ("auto", "none", "llm_consensus"),
            "must be \"auto\", \"llm_consensus\" or \"none\"")
        get("oracle_candidates", int, lambda v: 2 <= v <= len(llmgen.ORACLE_STYLES),
            f"must be 2..{len(llmgen.ORACLE_STYLES)}")
        get("min_examples_for_oracle", int, lambda v: v >= 0, "must be >= 0")
        get("max_case_families", int, lambda v: 1 <= v <= 20, "must be 1..20")
        get("known_solutions", int, lambda v: 0 <= v <= 5, "must be 0..5")
        get("max_input_bytes", int, lambda v: v > 0, "must be > 0")
        get("oracle_max_input_bytes", int, lambda v: v > 0, "must be > 0")
        get("description", str, lambda v: True, "must be a string")
        get("input_spec", dict, lambda v: True, "must be an object")
        ex = block.get("examples", [])
        if not isinstance(ex, list) or not all(isinstance(e, dict) and isinstance(e.get("input"), str)
                                               and isinstance(e.get("output"), str) for e in ex):
            problems.append("asset_generation.examples: must be a list of {\"input\": str, \"output\": str}")
        else:
            c.examples = [(e["input"], e["output"]) for e in ex]
        if raw.get("sample_output") is not None:
            if not isinstance(raw["sample_output"], str):
                problems.append("'sample_output' must be a string")
            elif isinstance(raw.get("sample_input"), str):
                c.examples.insert(0, (raw["sample_input"], raw["sample_output"]))
        for key, value in llm_overrides(overrides).items():
            if key == "provider" and value not in PROVIDERS:
                problems.append(f"LLM provider '{value}' is not one of {', '.join(PROVIDERS)}")
            else:
                setattr(c, key, value)
        return c, problems

    @property
    def oracle_enabled(self) -> bool:
        return self.oracle in ("auto", "llm_consensus")

    def public(self) -> Dict[str, Any]:
        return {k: v for k, v in self.__dict__.items() if k not in ("description", "input_spec", "examples")}


PROVIDERS = ("ollama", "groq", "openai_compat")


def llm_overrides(explicit: Optional[Dict[str, str]] = None) -> Dict[str, str]:
    """Provider/model chosen by whoever runs the grader: explicit values
    (CLI, UI) first, then AUTOGRADER_LLM_PROVIDER / AUTOGRADER_LLM_MODEL."""
    out = {}
    for key, env in (("provider", "AUTOGRADER_LLM_PROVIDER"), ("model", "AUTOGRADER_LLM_MODEL")):
        value = (explicit or {}).get(key) or os.environ.get(env, "")
        if isinstance(value, str) and value.strip():
            out[key] = value.strip()
    return out


