# -- 1. inventory -------------------------------------------------------------------
def _exists(base: Path, rel) -> bool:
    return isinstance(rel, str) and bool(rel) and (base / rel).exists()


def find_missing(raw: Dict[str, Any], base: Path) -> Dict[str, List[str]]:
    """Missing assets per metric (``"<rules>"`` for rules-level ones). Analyzers
    this module does not know (plugins) are left alone."""
    out: Dict[str, List[str]] = {}
    ref_named = raw.get("reference") is not None
    ref_ok = ref_named and _exists(base, raw["reference"])
    if ref_named and not ref_ok:
        out["<rules>"] = [f"reference solution {raw['reference']}"]
    for m in raw.get("metrics", []) if isinstance(raw.get("metrics"), list) else []:
        if not isinstance(m, dict) or not isinstance(m.get("params", {}), dict):
            continue
        name, analyzer, p = m.get("name"), m.get("analyzer"), m.get("params", {})
        miss: List[str] = []
        if analyzer == "io_tests":
            folder = base / p["testset_dir"] if isinstance(p.get("testset_dir"), str) else None
            tests = sorted(folder.glob("*.in")) if folder is not None and folder.is_dir() else []
            if folder is None or not folder.is_dir() or (not tests and not p.get("generated")):
                miss.append("test inputs")
            lacking = [t for t in tests if not t.with_suffix(".out").exists()]
            if lacking and not ref_ok:
                miss.append(f"expected outputs for {len(lacking)} test(s)")
            if p.get("generated"):
                if not ref_ok:
                    miss.append("a reference for generated tests")
                if not _exists(base, p.get("generator", "gen.py")):
                    miss.append("input generator")
        elif analyzer == "edge_case_runner":
            cf = p.get("cases_file", "edge_cases.json")
            if not _exists(base, cf):
                miss.append("corner cases")
            elif not ref_ok and not _all_expected(base / cf):
                miss.append("expected outputs for corner cases")
            if int(p.get("random_tests", 0) or 0) > 0:
                if not _exists(base, p.get("generator", "gen.py")):
                    miss.append("input generator")
                if not ref_ok:
                    miss.append("a reference for random tests")
        elif analyzer == "complexity_estimator":
            if not _exists(base, p.get("generator", "gen.py")):
                miss.append("input generator")
        elif analyzer == "sanitizer_run":
            if not _exists(base, p.get("cases_file", "edge_cases.json")):
                miss.append("extra inputs to replay (optional)")
        elif analyzer == "similarity_flag":
            for key in ("corpus_dir", "known_dir"):
                if p.get(key) and not (base / str(p[key])).is_dir():
                    miss.append(f"{key} {p[key]}")
        if miss:
            out[str(name)] = miss
    return out


def _all_expected(path: Path) -> bool:
    try:
        return all("expected" in p for ps in load_cases(path).values() for p in ps)
    except Exception:  # noqa: BLE001 - the rules check will report a broken file
        return False


def instructor_paths(raw: Dict[str, Any], base: Path) -> List[Path]:
    """Instructor files the generated assets depend on (cache invalidation)."""
    paths = []
    for rel in [raw.get("reference"), raw.get("statement"), "edge_cases.json", "gen.py"]:
        if _exists(base, rel):
            paths.append(base / rel)
    for m in raw.get("metrics", []):
        for v in (m.get("params", {}) or {}).values() if isinstance(m, dict) else []:
            if isinstance(v, str) and 0 < len(v) < 256 and _exists(base, v):
                paths.append(base / v)
    return paths


@dataclass
class Material:
    """What the instructor published, split by how it may be used."""
    inputs: List[str]                 # every instructor input (spec validation)
    examples: List[Tuple[str, str]]   # every instructor (input, output) pair (oracle validation)
    shown: List[Tuple[str, str]]      # the published sample pair, shown to the model
    sources: List[Dict[str, Any]]     # for the report / UI


def instructor_material(raw: Dict[str, Any], base: Path, cfg: Config) -> Material:
    sample = raw.get("sample_input") if isinstance(raw.get("sample_input"), str) else None
    examples = list(cfg.examples)
    sources: List[Dict[str, Any]] = []
    if sample is not None:
        sources.append({"name": "sample_input", "where": "rules.json",
                        "detail": "with sample_output" if isinstance(raw.get("sample_output"), str)
                        else "no sample_output"})
    n_ag = len(examples) - (1 if sample is not None and isinstance(raw.get("sample_output"), str) else 0)
    if n_ag:
        sources.append({"name": "asset_generation.examples", "where": "rules.json",
                        "detail": f"{n_ag} input/output pair(s), held out from the model"})
    test_inputs: List[str] = []
    for m in raw.get("metrics", []) if isinstance(raw.get("metrics"), list) else []:
        p = m.get("params", {}) if isinstance(m, dict) else {}
        if not (isinstance(m, dict) and m.get("analyzer") == "io_tests" and isinstance(p, dict)
                and isinstance(p.get("testset_dir"), str) and (base / p["testset_dir"]).is_dir()):
            continue
        pairs = 0
        for t in sorted((base / p["testset_dir"]).glob("*.in")):
            text = t.read_text(errors="replace")
            test_inputs.append(text)
            out = t.with_suffix(".out")
            if out.exists() and pairs < MAX_TEST_PAIRS:
                examples.append((text, out.read_text(errors="replace")))
                pairs += 1
        sources.append({"name": p["testset_dir"], "where": "problem folder",
                        "detail": f"{len(test_inputs)} test input(s), {pairs} with outputs"})
    for rel, what in ((raw.get("statement"), "statement"), (raw.get("reference"), "reference solution")):
        if isinstance(rel, str):
            sources.append({"name": rel, "where": "problem folder",
                            "detail": what + (" (found)" if _exists(base, rel) else " (named but missing)")})
    inputs: List[str] = []
    for text in ([sample] if sample is not None else []) + [i for i, _ in examples] + test_inputs:
        if text not in inputs:
            inputs.append(text)
    shown = [examples[0]] if examples and sample is not None and examples[0][0] == sample else []
    return Material(inputs, examples, shown, sources)


# -- entry point ----------------------------------------------------------------------
def prepare_assets(rules_path, llm: LLMClient, store: AssetStore, cache_root: Path,
                   submission: Optional[Path] = None,
                   overrides: Optional[Dict[str, str]] = None) -> Preparation:
    """``submission`` is used for one thing only: an input-format hint when the
    instructor published no input at all. ``overrides`` picks the LLM
    provider/model (see ``Config.from_rules``)."""
    path = Path(rules_path).resolve()
    try:
        text = path.read_text()
        raw = json.loads(text)
    except (OSError, ValueError):
        return Preparation(None, {})  # load_rules reports the problem properly
    if not isinstance(raw, dict):
        return Preparation(None, {})
    base = path.parent
    missing = find_missing(raw, base)
    if not missing:
        return Preparation(None, {})
    cfg, problems = Config.from_rules(raw, overrides)
    if cfg.input_spec is not None:
        problems += [f"asset_generation.input_spec: {p}" for p in check_spec(cfg.input_spec)]
    if problems:
        raise RulesError(path, problems)

    statement = ""
    if isinstance(raw.get("statement"), str) and _exists(base, raw["statement"]):
        statement = (base / raw["statement"]).read_text(errors="replace")
    if cfg.description:
        statement = (statement + "\n\n" + cfg.description).strip()
    material = instructor_material(raw, base, cfg)
    hint = ""
    if not material.inputs and cfg.input_spec is None and submission is not None and Path(submission).is_file():
        hint = llmgen.input_format_hint(Path(submission).read_text(errors="replace"))

    deps = {
        "generator_version": GENERATOR_VERSION, "prompt_version": llmgen.PROMPT_VERSION,
        "spec_version": SPEC_VERSION, "rules_sha256": hashlib.sha256(text.encode()).hexdigest(),
        "statement_sha256": hashlib.sha256(statement.encode()).hexdigest(),
        "instructor_assets": hash_paths(instructor_paths(raw, base)),
        "settings": cfg.public(), "compiler": tools.version(_cc(raw)),
    }
    if hint:
        deps["format_hint_sha256"] = hashlib.sha256(hint.encode()).hexdigest()
    key = hashlib.sha256(json.dumps(deps, sort_keys=True).encode()).hexdigest()
    digest = llm.model_identity(cfg.provider, cfg.model)
    problem = str(raw.get("problem") or "unknown")
    storage = f"{GENERATED_DIR}/{safe_name(problem, 'problem')}/{key[:16]}"

    bundle = store.get_bundle(key)
    if bundle is not None and digest and bundle["model_digest"] and digest != bundle["model_digest"]:
        store.delete_bundle(key)  # same model name, different weights: regenerate
        bundle = None
    if bundle is not None and bundle["manifest"].get("transient_failures") and not llm.offline:
        bundle = None  # built while the model was unreachable: try again
    cache_hit = bundle is not None
    if bundle is None:
        builder = _Builder(raw, base, cfg, statement, missing, llm, digest, material, hint, storage, key)
        manifest, records = builder.build()
        store.put_bundle(key, problem=problem, rules_sha256=deps["rules_sha256"],
                         dependencies=deps, provider=cfg.provider, model=cfg.model, model_digest=digest,
                         generator_version=GENERATOR_VERSION, manifest=manifest, assets=records,
                         events=builder.gen.events)
        bundle = store.get_bundle(key)
        assert bundle is not None
    manifest = bundle["manifest"]
    bundle_dir = Path(cache_root) / manifest.get("storage", storage)
    records = store.assets(key)
    materialize(records, bundle_dir, bundle_files(bundle, records))
    overlay = overlay_from_manifest(manifest, bundle_dir, key, bundle["model_digest"])
    return Preparation(overlay, missing, key, cache_hit, bundle_dir)


def _cc(raw) -> str:
    comp = raw.get("compile", {})
    return comp.get("cc", "gcc") if isinstance(comp, dict) else "gcc"


# -- 3-6. infer, generate, validate, decide -------------------------------------------
def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _family_name(name: str, i: int) -> str:
    clean = re.sub(r"[^a-z0-9_]+", "_", name.lower()).strip("_")[:40]
    return clean or f"family_{i}"


class _Builder:
    def __init__(self, raw, base: Path, cfg: Config, statement: str, missing, llm: LLMClient,
                 digest: Optional[str], material: Material, hint: str, storage: str, key: str):
        self.raw, self.base, self.cfg, self.statement, self.missing = raw, base, cfg, statement, missing
        self.material, self.hint, self.storage, self.key = material, hint, storage, key
        self.gen = llmgen.Generator(llm, llmgen.Settings(cfg.provider, cfg.model, cfg.seed, cfg.max_retries,
                                                                  digest))
        self.records: List[AssetRecord] = []
        self.failures: List[Dict[str, str]] = []
        self.metrics_out: Dict[str, Dict[str, Any]] = {}
        self.skipped: Dict[str, List[str]] = {}
        self.instructor_inputs = material.inputs
        self.example_out = {i: o for i, o in material.examples}
        self.metrics = [m for m in raw.get("metrics", []) if isinstance(m, dict)]
        self.ref_ok = raw.get("reference") is not None and _exists(base, raw["reference"])
        self.spec_basis = ""
        self.oracle_info: Dict[str, Any] = {"mode": "not_needed", "reason": ""}
        self.no_expected_reason = "no instructor reference and no validated oracle"
        self.disagreements: Dict[str, Dict[str, str]] = {}
        self.brief = llmgen.problem_brief(
            llmgen.humanize_title(raw.get("problem", "")), statement, material.shown,
            [raw["sample_input"]] if isinstance(raw.get("sample_input"), str) else [],
            self._limits(), self._hints())

    # -- helpers ------------------------------------------------------------------
    def _limits(self) -> Dict[str, Any]:
        req = next(((m.get("params") or {}).get("required") for m in self.metrics
                    if m.get("analyzer") == "complexity_estimator"), None)
        return {"time_limit_s": self.raw.get("time_limit_s"), "memory_limit_mb": self.raw.get("memory_limit_mb"),
                "required_complexity": req}

    def _hints(self) -> Dict[str, Any]:
        fams = []
        for m in self.metrics:
            c = (m.get("params") or {}).get("cases") if m.get("analyzer") == "edge_case_runner" else None
            if isinstance(c, list):
                fams += [str(x) for x in c]
        compare = next(((m.get("params") or {}).get("compare") for m in self.metrics
                        if (m.get("params") or {}).get("compare")), None)
        return {"case_families": fams, "compare": compare}

    def add(self, kind, name, status, origin, detail="", content=None, path=None) -> AssetRecord:
        rec = AssetRecord(kind, name, status, origin, detail, content, path,
                          _sha(content) if content is not None else None)
        self.records.append(rec)
        return rec

    def fail(self, step: str, detail: str) -> None:
        self.failures.append({"step": step, "detail": detail})

    def _metrics(self, analyzer: str) -> List[Dict[str, Any]]:
        return [m for m in self.metrics if m.get("analyzer") == analyzer and str(m.get("name")) in self.missing]

    # -- build -----------------------------------------------------------------
    def build(self) -> Tuple[Dict[str, Any], List[AssetRecord]]:
        need_gen = any("input generator" in v for v in self.missing.values())
        need_inputs = any(m in self.missing for m in
                          [str(x.get("name")) for x in self.metrics
                           if x.get("analyzer") in ("io_tests", "edge_case_runner", "sanitizer_run")])
        self.spec = self._input_spec() if (need_gen or need_inputs) else None
        self.gen_rel = self._generator() if self.spec is not None else None
        self.pool = self._input_pool() if self.spec is not None else {}
        self.random_plan = self._random_plan()
        self.expected_kind, self.oracle_rel, self.oracle_out = self._oracle()
        self.known_rel = self._known() if any("known_dir" in " ".join(v) for v in self.missing.values()) else None

        overlay_params: Dict[str, Dict[str, Any]] = {}
        not_performed: Dict[str, str] = {}
        for m in self.metrics:
            name = str(m.get("name"))
            if name not in self.missing:
                continue
            decide = getattr(self, f"_decide_{m.get('analyzer')}", None)
            if decide is None:
                continue
            status, detail, over = decide(name, m.get("params", {}) or {})
            self.metrics_out[name] = {"analyzer": m.get("analyzer"), "status": status, "detail": detail,
                                      "missing": self.missing[name], "overrides": over,
                                      "skipped": _dedupe(self.skipped.get(name, []))}
            if status == "not_performed":
                not_performed[name] = detail
            elif over:
                overlay_params[name] = over

        reference = None
        replace_reference = False
        if self.oracle_rel:
            reference, replace_reference = self.oracle_rel, True
        elif "<rules>" in self.missing:
            replace_reference = True  # named but missing: grade without it
        manifest = {
            "generation_id": self.key[:16], "storage": self.storage,
            "llm": {"provider": self.cfg.provider, "model": self.cfg.model},
            "expected_outputs_from": self.expected_kind,
            "spec_basis": self.spec_basis, "oracle": self.oracle_info,
            "instructor_material": self.material.sources,
            "metrics": self.metrics_out, "params": overlay_params, "not_performed": not_performed,
            "reference": reference, "replace_reference": replace_reference,
            "failures": self.failures, "missing": self.missing,
            # True when the LLM was unreachable: kept for the audit trail, but
            # regenerated on the next run that can reach the model
            "transient_failures": any(r.status == "unavailable" and "LLM unavailable" in r.detail
                                      for r in self.records),
            "counts": {"generated": sum(r.origin in ORIGIN_GENERATED and r.status in ("validated", "rejected")
                                        for r in self.records),
                       **{s: sum(r.status == s for r in self.records)
                          for s in ("validated", "rejected", "skipped", "unavailable")}},
        }
        return manifest, self.records

    # -- input spec + generator ------------------------------------------------------
    def _input_spec(self) -> Optional[InputSpec]:
        n_inputs = len(self.instructor_inputs)
        if self.cfg.input_spec is not None:
            spec, origin = self.cfg.input_spec, "instructor"
            self.spec_basis = "instructor (asset_generation.input_spec)"
            problems = [f"instructor input {i} does not match: {e[0]}"
                        for i, s in enumerate(self.instructor_inputs, 1) for e in [InputSpec(spec).validate(s)] if e]
        else:
            spec, origin = llmgen.propose_input_spec(self.gen, self.brief, self.instructor_inputs, self.hint), "llm"
            problems = [] if spec is not None else [f"no valid input specification ({self.gen.last_error})"]
            if n_inputs:
                self.spec_basis = f"inferred by the LLM from the problem brief; checked against {n_inputs} instructor input(s)"
            elif self.hint:
                self.spec_basis = ("inferred by the LLM from the problem title and the submission's input-reading "
                                   "statements; NOT checked against any instructor input (none was given)")
            else:
                self.spec_basis = ("inferred by the LLM from the problem title only; NOT checked against any "
                                   "instructor input (none was given)")
        if problems:
            status = self.gen.failed_status() if origin == "llm" else "rejected"
            self.add("input_spec", "input_spec.json", status, origin, "; ".join(problems),
                     json.dumps(spec, sort_keys=True) if spec is not None else None)
            self.fail("input_spec", "; ".join(problems))
            return None
        detail = f"accepts all {n_inputs} instructor input(s)" if n_inputs else self.spec_basis
        self.add("input_spec", "input_spec.json", "validated", origin, detail,
                 json.dumps(spec, indent=2, sort_keys=True) + "\n", SPEC_FILE)
        return InputSpec(spec)

    def _generator(self) -> Optional[str]:
        spec = self.spec
        assert spec is not None
        content = GEN_TEMPLATE.format(version=GENERATOR_VERSION, spec_json=json.dumps(spec.spec, sort_keys=True))
        sizes = sorted({s for s in [1, 2, 3, 5, 8, 13] if spec.supports_size(s)} |
                       {s for s in self._requested_sizes() if spec.supports_size(s)})
        problems = []
        for size in sizes:
            try:
                a = spec.generate(size, seeded_rng(self.cfg.seed, "check", size))
                b = spec.generate(size, seeded_rng(self.cfg.seed, "check", size))
            except SpecError as e:
                problems.append(f"size {size}: {e}")
                continue
            if a != b:
                problems.append(f"not deterministic at size {size}")
            err = spec.validate(a)
            if err:
                problems.append(f"size {size}: generated input breaks the spec: {err[0]}")
        if problems:
            self.add("generator", "gen.py", "rejected", "deterministic", "; ".join(problems), content)
            self.fail("generator", "; ".join(problems))
            return None
        self.add("generator", "gen.py", "validated", "deterministic",
                 f"deterministic and spec-valid at sizes {sizes}", content, GEN_FILE)
        return GEN_FILE

    def _requested_sizes(self) -> List[int]:
        out = []
        for m in self.metrics:
            p = m.get("params", {}) or {}
            if m.get("analyzer") == "complexity_estimator":
                out += [s for s in p.get("sizes", []) if isinstance(s, int)]
            elif m.get("analyzer") == "edge_case_runner" and int(p.get("random_tests", 0) or 0) > 0:
                out += [s for s in p.get("sizes", DEFAULT_SIZES) if isinstance(s, int)]
            elif m.get("analyzer") == "io_tests":
                out += [g["size"] for g in p.get("generated", []) if isinstance(g, dict) and isinstance(g.get("size"), int)]
        return out

    def _fit_sizes(self, sizes: List[int], minimum: int) -> Tuple[Optional[List[int]], str]:
        """(usable sizes, note). Sizes outside the input's range are dropped;
        fewer than ``minimum`` left -> (None, why)."""
        if self.spec is None:
            return None, "no validated input generator"
        ok = [s for s in sizes if isinstance(s, int) and self.spec.supports_size(s)]
        bad = [s for s in sizes if s not in ok]
        r = self.spec.size_range()
        where = f"the input's allowed range {list(r)}" if r else "the input's allowed range"
        if len(ok) < minimum:
            return None, (f"requested size(s) {bad} are outside {where}; {len(ok)} usable, "
                          f"{minimum} needed")
        return ok, (f"size(s) {bad} outside {where} dropped" if bad else "")

    # -- input pool ----------------------------------------------------------------------
    def _input_pool(self) -> Dict[str, List[Tuple[str, str]]]:
        """family -> [(input, origin)], every input validated against the spec."""
        spec = self.spec
        assert spec is not None
        pool: Dict[str, List[Tuple[str, str]]] = {}
        seen = set(self.instructor_inputs)

        def offer(family: str, text: str, origin: str) -> None:
            label = f"{family}/{len(pool.get(family, [])) + 1}"
            if not isinstance(text, str):
                return
            text = text if text.endswith("\n") else text + "\n"
            errs = spec.validate(text)
            if not errs and len(text) > self.cfg.max_input_bytes:
                errs = [f"larger than {self.cfg.max_input_bytes} bytes"]
            if errs:
                self.add("test_input", label, "rejected", origin, errs[0], text[:2000])
                return
            if text in seen:
                return
            seen.add(text)
            pool.setdefault(family, []).append((text, origin))
            self.add("test_input", label, "validated", origin, "matches the input spec", text)

        for fam, texts in spec.boundary_cases(seeded_rng(self.cfg.seed, "boundary"), self.cfg.max_input_bytes).items():
            for t in texts:
                offer(fam, t, "deterministic")
        for i, size in enumerate(s for s in [1, 2, 3, 5, 8, 13, 20] if spec.supports_size(s)):
            offer("random_small", spec.generate(size, seeded_rng(self.cfg.seed, "pool", size, i)), "deterministic")

        wanted = None
        for m in self._metrics("edge_case_runner"):
            c = (m.get("params", {}) or {}).get("cases", "all")
            if isinstance(c, list) and not _exists(self.base, (m.get("params") or {}).get("cases_file", "edge_cases.json")):
                wanted = [str(x) for x in c]
        families = llmgen.propose_case_families(self.gen, self.brief, spec.spec, wanted, self.cfg.max_case_families)
        if families is None:
            self.add("test_input", "llm_case_families", self.gen.failed_status(), "llm", self.gen.last_error)
            self.fail("case_families", f"no valid corner-case answer ({self.gen.last_error}); "
                                       "using deterministic boundary cases only")
        else:
            for i, f in enumerate(families, 1):
                name = f["name"] if wanted and f["name"] in wanted else _family_name(f["name"], i)
                if name in ("random_small", "random_stress") or (name in pool and not wanted):
                    name = f"llm_{name}"
                for t in f["inputs"]:
                    offer(name, t, "llm")
        return pool

    def _random_plan(self) -> Dict[str, Dict[str, Any]]:
        """Random stress tests the corner-case runner will draw at grade time,
        computed here too so the oracle is validated on exactly those inputs."""
        plan: Dict[str, Dict[str, Any]] = {}
        for m in self._metrics("edge_case_runner"):
            p = m.get("params", {}) or {}
            n = int(p.get("random_tests", 0) or 0)
            if n <= 0 or _exists(self.base, p.get("generator", "gen.py")) or self.spec is None:
                continue
            sizes, note = self._fit_sizes(list(p.get("sizes", DEFAULT_SIZES)), 1)
            entry: Dict[str, Any] = {"n": n, "sizes": sizes, "note": note, "inputs": []}
            if sizes:
                seed = p.get("seed", 42)
                entry["inputs"] = [self.spec.generate(sizes[i * len(sizes) // n],
                                                      seeded_rng(seed, "edge", sizes[i * len(sizes) // n], i))
                                   for i in range(n)]
            plan[str(m.get("name"))] = entry
        return plan

    # -- expected outputs --------------------------------------------------------------
    def _needs_expected(self) -> bool:
        return any(m.get("analyzer") in ("io_tests", "edge_case_runner") for m in
                   [x for x in self.metrics if str(x.get("name")) in self.missing])

    def _fallback_kind(self) -> str:
        return "instructor_outputs" if self.example_out else "none"

    def _oracle(self) -> Tuple[str, Optional[str], Dict[str, str]]:
        if self.ref_ok:
            self.oracle_info = {"mode": "instructor_reference", "reason": "the instructor's reference solution"}
            return "instructor_reference", None, {}
        if not self._needs_expected():
            return "not_needed", None, {}
        if not self.cfg.oracle_enabled:
            why = "no instructor reference, and the LLM oracle is turned off (asset_generation.oracle = \"none\")"
            self.add("oracle", "oracle", "unavailable", "llm_oracle", why)
            self.oracle_info = {"mode": "off", "reason": why}
            self.no_expected_reason = why
            return self._fallback_kind(), None, {}

        comp = self.raw.get("compile", {}) if isinstance(self.raw.get("compile"), dict) else {}
        runner = CandidateRunner(_cc(self.raw), split_flags(comp.get("flags", "-O2 -std=c11")),
                                 split_flags(comp.get("ldflags", "-lm")),
                                 float(self.raw.get("time_limit_s", 1)), int(self.raw.get("memory_limit_mb", 256)))
        examples = self.material.examples
        anchored = bool(examples)
        labels = ORACLE_LABELS[: self.cfg.oracle_candidates]
        min_agreeing = 2 if anchored else len(labels)
        try:
            codes = []
            for i, label in enumerate(labels):
                code = llmgen.propose_program(
                    self.gen, f"oracle:{label}", self.brief, llmgen.ORACLE_STYLES[i],
                    lambda c, lb=label: compile_problems(runner, c, f"check-{lb}"), seed_offset=100 + i)
                if code is None:
                    self.add("oracle", f"{label}.c", self.gen.failed_status(), "llm_oracle",
                             f"no program that passes the static screen and compiles ({self.gen.last_error})")
                else:
                    codes.append((label, code))
            if not codes:
                why = f"no oracle program could be generated ({self.gen.last_error})"
                self.fail("oracle", why)
                self.oracle_info = {"mode": "rejected", "reason": why, "candidates": []}
                self.no_expected_reason = "no instructor reference, and " + why
                return self._fallback_kind(), None, {}
            validation = self._validation_inputs()
            compare = next(((m.get("params") or {}).get("compare", "trim") for m in self.metrics
                            if m.get("analyzer") == "io_tests"), "trim")
            verdict = select_oracle(runner, codes, examples, validation, compare,
                                    self.cfg.min_examples_for_oracle, min_agreeing)
        finally:
            runner.close()
        for c in verdict.candidates:
            ok = c.ok and verdict.mode != "rejected"
            self.add("oracle", f"{c.label}.c", "validated" if ok else "rejected", "llm_oracle",
                     verdict.reason if c.ok else "; ".join(c.problems), c.code, f"oracles/{c.label}.c")
        self.disagreements = verdict.disagreements
        self.oracle_info = {
            "mode": verdict.mode, "reason": verdict.reason, "anchored_on_examples": len(examples),
            "shown_to_model": len(self.material.shown), "required_agreeing": min_agreeing,
            "validation_inputs": len(validation), "agreed_inputs": len(verdict.expected),
            "disagreeing_inputs": len(verdict.disagreements),
            "candidates": [{"label": c.label, "status": "ok" if c.ok else "rejected",
                            "detail": "; ".join(c.problems)} for c in verdict.candidates],
        }
        if verdict.mode == "rejected":
            self.fail("oracle", verdict.reason)
            self.no_expected_reason = "no instructor reference, and the LLM oracle was rejected: " + verdict.reason
            return self._fallback_kind(), None, {}
        if verdict.mode == "partial":
            self.fail("oracle", verdict.reason)
            self.no_expected_reason = ("the oracle candidates disagree on this input, so it has no trustworthy "
                                       "expected output")
            return "llm_consensus_inputs", None, verdict.expected
        assert verdict.accepted is not None
        self.add("reference", "reference.c", "validated", "llm_oracle",
                 f"generated reference solution ({verdict.accepted.label}): {verdict.reason}",
                 verdict.accepted.code, REFERENCE_FILE)
        return "llm_consensus_oracle", REFERENCE_FILE, verdict.expected

    def _validation_inputs(self) -> List[str]:
        out: List[str] = []
        texts = [t for fam in self.pool.values() for t, _ in fam]
        texts += [t for plan in self.random_plan.values() for t in plan["inputs"]]
        texts += [t for t in self.instructor_inputs if t not in self.example_out]
        for t in texts:
            if len(t) <= self.cfg.oracle_max_input_bytes and t not in out:
                out.append(t)
        return out

    def _expected(self, text: str) -> Tuple[bool, Optional[str], str]:
        """(can this input be checked, its stored expected output or None when
        the reference computes it at grade time, why not)."""
        if text in self.example_out:
            return True, self.example_out[text], ""
        if self.expected_kind == "instructor_reference":
            return True, None, ""
        if text in self.oracle_out:
            return True, self.oracle_out[text], ""
        if self.expected_kind == "llm_consensus_oracle":
            return False, None, (f"larger than oracle_max_input_bytes ({self.cfg.oracle_max_input_bytes}), "
                                 "so the oracle candidates were not cross-checked on it")
        if text in self.disagreements:
            outs = ", ".join(f"{lb} -> {o.strip()[:30]!r}" for lb, o in self.disagreements[text].items())
            return False, None, f"oracle candidates disagree ({outs})"
        return False, None, self.no_expected_reason

    def _trusted_for_unseen(self) -> bool:
        return self.expected_kind in ("instructor_reference", "llm_consensus_oracle")

    # -- known solutions --------------------------------------------------------------
    def _known(self) -> Optional[str]:
        if self.cfg.known_solutions == 0:
            self.add("known_solution", "known", "unavailable", "llm", "asset_generation.known_solutions is 0")
            return None
        safe = re.sub(r"[^A-Za-z0-9.]+", "-", self.cfg.model)
        sources = {}
        for i in range(self.cfg.known_solutions):
            code = llmgen.propose_program(
                self.gen, f"known:{i + 1}", self.brief, llmgen.ORACLE_STYLES[i % len(llmgen.ORACLE_STYLES)],
                lambda c: [] if re.search(r"\bmain\s*\(", c) and len(c) < 50_000 else ["not a C program"],
                seed_offset=200 + i)
            name = f"llm_{safe}_{i + 1}.c"
            if code is None:
                self.add("known_solution", name, self.gen.failed_status(), "llm",
                         f"no usable program ({self.gen.last_error})")
                continue
            # compared as text only; never compiled or run
            self.add("known_solution", name, "validated", "llm", "text-only comparison corpus", code, f"known/{name}")
            sources[name] = f"LLM-generated ({self.cfg.model})"
        if not sources:
            self.fail("known_solutions", f"no LLM solution could be generated ({self.gen.last_error})")
            return None
        self.add("known_solution", "sources.json", "validated", "llm", "labels",
                 json.dumps(sources, indent=2, sort_keys=True) + "\n", "known/sources.json")
        return "known"

    # -- per-analyzer decisions: (status, detail, param overrides) -------------------------
    def _pool_items(self) -> List[Tuple[str, str, str]]:
        return [(fam, t, o) for fam, items in self.pool.items() for t, o in items]

    def _skip(self, metric: str, what: str, why: str) -> None:
        self.skipped.setdefault(metric, []).append(f"{what}: {why}")

    def _decide_io_tests(self, name, p):
        over: Dict[str, Any] = {}
        folder = self.base / p["testset_dir"] if isinstance(p.get("testset_dir"), str) else None
        tests = sorted(folder.glob("*.in")) if folder is not None and folder.is_dir() else []
        rel = f"tests/{safe_name(name, 'metric')}"
        files: List[Tuple[str, str, Optional[str], str]] = []  # (stem, input, output, origin)
        if tests:
            for t in tests:
                out = t.with_suffix(".out")
                if out.exists():
                    files.append((t.stem, t.read_text(), out.read_text(), "instructor"))
                    continue
                ok, exp, why = self._expected(t.read_text())
                if ok:
                    files.append((t.stem, t.read_text(), exp, "instructor"))
                else:
                    self._skip(name, f"test {t.stem}", why)
            materialize_needed = bool(self.skipped.get(name)) or \
                any(f[2] is not None and not (folder / f"{f[0]}.out").exists() for f in files)
        else:
            for i, (inp, out) in enumerate(self.material.examples, 1):
                files.append((f"ex{i:02d}", inp, out, "instructor_example"))
            n = 0
            for fam, text, origin in self._pool_items():
                ok, exp, why = self._expected(text)
                if ok:
                    n += 1
                    files.append((f"g{n:03d}_{fam}"[:60], text, exp, origin))
                else:
                    self._skip(name, fam, why)
            materialize_needed = True
        if materialize_needed and files:
            for stem, inp, out, origin in files:
                self.add("test_input", f"{name}/{stem}.in", "validated", origin, "", inp, f"{rel}/{stem}.in")
                if out is not None:
                    src = origin if origin.startswith("instructor") else "llm_oracle"
                    self.add("test_output", f"{name}/{stem}.out", "validated", src,
                             "instructor output" if origin.startswith("instructor") else
                             "agreed output of the oracle candidates", out, f"{rel}/{stem}.out")
            over["testset_dir"] = f"{ASSETS_PREFIX}/{rel}"

        gen_specs = [g for g in p.get("generated", []) if isinstance(g, dict)]
        n_generated = len(gen_specs)
        if gen_specs:
            if not self._trusted_for_unseen():
                over["generated"] = []
                self._skip(name, f"{n_generated} generated hidden test(s)",
                           "no program is trusted as a reference for unseen inputs (" + self.no_expected_reason + ")")
                n_generated = 0
            elif not _exists(self.base, p.get("generator", "gen.py")):
                keep = [g for g in gen_specs if self.spec is not None and isinstance(g.get("size"), int)
                        and self.spec.supports_size(g["size"])]
                if not self.gen_rel or not keep:
                    over["generated"] = []
                    why = "no validated input generator" if not self.gen_rel else \
                        self._fit_sizes([g.get("size") for g in gen_specs], 1)[1]
                    self._skip(name, f"{n_generated} generated hidden test(s)", why)
                    n_generated = 0
                else:
                    if len(keep) < n_generated:
                        self._skip(name, f"{n_generated - len(keep)} generated hidden test(s)",
                                   "size outside the input's allowed range")
                        over["generated"] = keep
                    n_generated = len(keep)
                    over["generator"] = f"{ASSETS_PREFIX}/{self.gen_rel}"
        skipped = self.skipped.get(name, [])
        for s in _dedupe(skipped):
            self.add("test_input", f"{name}: {s.split(':')[0]}", "skipped", "deterministic", s)
        performed = len(files) + n_generated
        if performed == 0:
            return "not_performed", self._why_no_expected("correctness tests"), {}
        detail = f"{len(files)} test(s)" + (f" + {n_generated} generated" if n_generated else "") + \
                 f"; expected outputs from {self.expected_kind.replace('_', ' ')}"
        if skipped:
            return "partial", detail + f"; {len(skipped)} skipped", over
        return "prepared", detail, over

    def _why_no_expected(self, what: str) -> str:
        outputs = ("the instructor's example outputs cover only the correctness examples"
                   if self.example_out else "there are no instructor outputs")
        return (f"no trustworthy expected outputs for {what}: {self.no_expected_reason}; {outputs}. "
                f"The submission's own output is never used as the answer key.")

    def _decide_edge_case_runner(self, name, p):
        over: Dict[str, Any] = {}
        cf_rel = p.get("cases_file", "edge_cases.json")
        wanted = p.get("cases", "all")
        rel = f"edge_cases/{safe_name(name, 'metric')}.json"
        fams: Dict[str, List[dict]] = {}
        if _exists(self.base, cf_rel):
            for fam, probes in load_cases(self.base / cf_rel).items():
                for probe in probes:
                    ok, exp, why = (True, probe["expected"], "") if "expected" in probe else \
                        self._expected(probe["input"])
                    if ok:
                        fams.setdefault(fam, []).append({**probe, **({"expected": exp} if exp is not None else {})})
                    else:
                        self._skip(name, fam, why)
            origin = "instructor"
        else:
            for fam, text, o in self._pool_items():
                if isinstance(wanted, list) and fam not in wanted:
                    continue
                ok, exp, why = self._expected(text)
                if ok:
                    fams.setdefault(fam, []).append({"input": text, **({"expected": exp} if exp is not None else {})})
                else:
                    self._skip(name, fam, why)
            origin = "generated"
        if isinstance(wanted, list):
            missing_fams = [w for w in wanted if w not in fams]
            for w in missing_fams:
                self._skip(name, w, "family could not be generated, or none of its inputs could be checked")
            if missing_fams:
                over["cases"] = [w for w in wanted if w in fams]
        probes = sum(len(v) for v in fams.values())
        if probes:
            self.add("edge_cases", f"{name}/{Path(rel).name}", "validated", origin,
                     f"{probes} probe(s) in {len(fams)} family(ies)", json.dumps(fams, indent=2) + "\n", rel)
        over["cases_file"] = f"{ASSETS_PREFIX}/{rel}"

        n_random = int(p.get("random_tests", 0) or 0)
        if n_random > 0 and not _exists(self.base, p.get("generator", "gen.py")):
            plan = self.random_plan.get(name, {})
            if not self._trusted_for_unseen():
                over["random_tests"] = 0
                self._skip(name, f"{n_random} random stress test(s)",
                           "no program is trusted as a reference for unseen inputs (" + self.no_expected_reason + ")")
                n_random = 0
            elif not plan.get("sizes"):
                over["random_tests"] = 0
                self._skip(name, f"{n_random} random stress test(s)", plan.get("note") or "no validated input generator")
                n_random = 0
            else:
                over["generator"] = f"{ASSETS_PREFIX}/{self.gen_rel}"
                if plan["sizes"] != list(p.get("sizes", DEFAULT_SIZES)):
                    over["sizes"] = plan["sizes"]
                    self._skip(name, "random stress sizes", plan["note"])
        skipped = self.skipped.get(name, [])
        for s in _dedupe(skipped):
            self.add("test_input", f"{name}: {s.split(':')[0]}", "skipped", "deterministic", s)
        if probes + n_random == 0:
            return "not_performed", self._why_no_expected("corner cases"), {}
        detail = f"{probes} corner-case probe(s) in {len(fams)} family(ies)" + \
                 (f" + {n_random} random" if n_random else "") + \
                 f"; expected outputs from {self.expected_kind.replace('_', ' ')}"
        return ("partial" if skipped else "prepared"), detail + (f"; {len(skipped)} skipped" if skipped else ""), over

    def _decide_complexity_estimator(self, name, p):
        if _exists(self.base, p.get("generator", "gen.py")):
            return "ready", "instructor generator", {}
        if not self.gen_rel:
            why = next((f["detail"] for f in self.failures if f["step"] in ("input_spec", "generator")),
                       "the input format could not be established")
            return "not_performed", f"no input generator: {why}", {}
        sizes, note = self._fit_sizes([s for s in p.get("sizes", []) if isinstance(s, int)], 3)
        if sizes is None:
            return "not_performed", note, {}
        over = {"generator": f"{ASSETS_PREFIX}/{self.gen_rel}"}
        detail = f"generated input generator (validated spec, deterministic), sizes {sorted(sizes)}"
        if note:
            over["sizes"] = sizes
            detail += f"; {note}"
        return "prepared", detail, over

    def _decide_sanitizer_run(self, name, p):
        items = [t for _, t, _ in self._pool_items()] + [i for i in self.instructor_inputs]
        if not items:
            return "ready", "sample input and any test inputs only", {}
        if not any(r.path == REPLAY_FILE for r in self.records):
            self.add("inputs", "replay_inputs.json", "validated", "deterministic" if self.pool else "instructor",
                     f"{len(items)} validated input(s)",
                     json.dumps({"generated_inputs": items}, indent=2) + "\n", REPLAY_FILE)
        return "prepared", f"{len(items)} validated input(s) to replay (instructor + generated)", \
            {"cases_file": f"{ASSETS_PREFIX}/{REPLAY_FILE}"}

    def _decide_similarity_flag(self, name, p):
        over: Dict[str, Any] = {}
        notes = []
        for key in ("corpus_dir", "known_dir"):
            if p.get(key) and not (self.base / str(p[key])).is_dir():
                if key == "known_dir" and self.known_rel:
                    over[key] = f"{ASSETS_PREFIX}/{self.known_rel}"
                    notes.append("known solutions generated by the LLM")
                else:
                    over[key] = ""
                    notes.append(f"{key} {p[key]} not found and cannot be generated")
        remaining = [k for k in ("corpus_dir", "known_dir") if over.get(k, p.get(k))]
        if not remaining:
            return "not_performed", "; ".join(notes) + "; nothing to compare against", {}
        return ("partial" if any("cannot" in n for n in notes) else "prepared"), "; ".join(notes), over


def _dedupe(items: List[str]) -> List[str]:
    return list(dict.fromkeys(items))


# -- 7. materialise + overlay ----------------------------------------------------------
def _safe_path(root: Path, rel: str) -> Path:
    p = (root / rel).resolve()
    if rel.startswith("/") or ".." in Path(rel).parts or root.resolve() not in p.parents:
        raise ValueError(f"unsafe asset path {rel!r}")
    return p


def bundle_files(bundle: Dict[str, Any], records: List[AssetRecord]) -> Dict[str, str]:
    """The two summary files written next to the assets: what was decided, and
    every asset's validation result (rejected ones included, with content)."""
    manifest = {k: v for k, v in bundle["manifest"].items() if k != "params"}
    manifest.update({"bundle_key": bundle["bundle_key"], "provider": bundle["model_provider"],
                     "model": bundle["model_name"], "model_digest": bundle["model_digest"],
                     "generator_version": bundle["generator_version"], "created_at": bundle["created_at"]})
    report = [{"kind": r.kind, "name": r.name, "status": r.status, "origin": r.origin, "detail": r.detail,
               "file": r.path, "sha256": r.sha256,
               **({"content": (r.content or "")[:2000]} if r.content is not None and not r.path else {})}
              for r in records]
    return {MANIFEST_FILE: json.dumps(manifest, indent=2, sort_keys=True) + "\n",
            REPORT_FILE: json.dumps({"bundle_key": bundle["bundle_key"], "assets": report}, indent=2) + "\n"}


def materialize(records: List[AssetRecord], bundle_dir: Path, extra: Optional[Dict[str, str]] = None) -> None:
    """Write the bundle's files so the folder holds exactly them (an extra or
    edited file would silently change the test set, so the folder is rebuilt
    whenever it differs from the database). Analyzers are only ever pointed at
    validated files; rejected oracle candidates are kept for review."""
    files = {r.path: r.content or "" for r in records if r.path}
    files.update(extra or {})
    if bundle_dir.is_dir() and _dir_matches(bundle_dir, files):
        return
    bundle_dir.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=".tmp-", dir=str(bundle_dir.parent)))
    for rel, content in files.items():
        dst = _safe_path(tmp, rel)
        dst.parent.mkdir(parents=True, exist_ok=True)
        with open(dst, "w", newline="\n") as fh:  # LF on every host, Windows included
            fh.write(content)
    shutil.rmtree(bundle_dir, ignore_errors=True)
    try:
        tmp.rename(bundle_dir)
    except OSError:  # a concurrent grader materialised the same bundle first
        shutil.rmtree(tmp, ignore_errors=True)


def _dir_matches(root: Path, files: Dict[str, str]) -> bool:
    on_disk = {f.relative_to(root).as_posix() for f in root.rglob("*") if f.is_file()}
    if on_disk != set(files):
        return False
    return all((root / rel).read_text() == content for rel, content in files.items())


def _abs(value, bundle_dir: Path):
    if isinstance(value, str) and value.startswith(ASSETS_PREFIX):
        rel = value[len(ASSETS_PREFIX):].lstrip("/")
        return str(_safe_path(bundle_dir, rel))
    return value


def overlay_from_manifest(manifest: Dict[str, Any], bundle_dir: Path, key: str,
                          model_digest: Optional[str]) -> AssetOverlay:
    params = {m: {k: _abs(v, bundle_dir) for k, v in over.items()} for m, over in manifest["params"].items()}
    reference = _safe_path(bundle_dir, manifest["reference"]) if manifest.get("reference") else None
    report = build_report_section(manifest, key, model_digest)
    return AssetOverlay(params=params, not_performed=dict(manifest["not_performed"]), reference=reference,
                        replace_reference=bool(manifest.get("replace_reference")), report=report)


def build_report_section(manifest: Dict[str, Any], key: str, model_digest: Optional[str]) -> Dict[str, Any]:
    """The ``asset_preparation`` part of the report. Only deterministic content
    (no timings, no cache-hit flag, no absolute paths), so the fingerprint is the
    same on every machine and on every re-run."""
    flags = []
    kind = manifest["expected_outputs_from"]
    oracle = manifest.get("oracle", {})
    if kind in ("llm_consensus_oracle", "llm_consensus_inputs"):
        anchored = oracle.get("anchored_on_examples", 0)
        flags.append({"type": "llm_oracle_used",
                      "detail": "Some expected outputs come from independent LLM-written programs that "
                                + (f"reproduced all {anchored} instructor example(s) and " if anchored else "")
                                + "agreed with each other on every input they are used for. That is evidence, "
                                  "not proof: review before publishing."})
        if not anchored:
            flags.append({"type": "llm_oracle_unanchored",
                          "detail": "No instructor example output exists, so the oracle is pure consensus of "
                                    f"{oracle.get('required_agreeing')} independent programs. Add sample_output "
                                    "(or asset_generation.examples) to anchor it."})
    if manifest.get("spec_basis", "").find("submission") != -1:
        flags.append({"type": "input_format_from_submission",
                      "detail": "No instructor input exists; the input format was inferred with the submission's "
                                "input-reading code as a hint. Add sample_input to remove this dependency."})
    for f in manifest["failures"]:
        flags.append({"type": "asset_generation_failed", "detail": f"{f['step']}: {f['detail']}"})
    partial = [n for n, m in manifest["metrics"].items() if m["status"] == "partial"]
    if partial:
        flags.append({"type": "tests_incomplete",
                      "detail": f"Parts of {', '.join(partial)} could not be prepared and were skipped "
                                f"(see asset_preparation); their scores cover only what actually ran."})
    return {
        "bundle_key": key, "generation_id": manifest.get("generation_id", key[:16]),
        "storage": manifest.get("storage"), "generator_version": GENERATOR_VERSION,
        "llm": manifest.get("llm"), "model_digest": model_digest,
        "expected_outputs_from": kind, "spec_basis": manifest.get("spec_basis", ""),
        "oracle": {k: v for k, v in oracle.items() if k != "candidates"} |
                  ({"candidates": oracle["candidates"]} if oracle.get("candidates") else {}),
        "assets": manifest.get("counts", {}),
        "metrics": {n: {k: v for k, v in m.items() if k != "overrides"} | {"overrides": sorted(m["overrides"])}
                    for n, m in manifest["metrics"].items()},
        "failures": manifest["failures"],
        "flags": flags,
    }
