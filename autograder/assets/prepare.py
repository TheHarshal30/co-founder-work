# -- configuration (the optional "asset_generation" block of the rules) ----------
@dataclass
class Config:
    provider: str = "ollama"
    model: str = "qwen2.5:7b"
    seed: int = 42
    max_retries: int = 3
    oracle: str = "none"  # none | llm_consensus
    oracle_candidates: int = 3
    min_examples_for_oracle: int = 2
    max_case_families: int = 6
    known_solutions: int = 3
    max_input_bytes: int = 50_000
    oracle_max_input_bytes: int = 4_000
    description: str = ""
    input_spec: Optional[dict] = None
    examples: List[Tuple[str, str]] = field(default_factory=list)

    @classmethod
    def from_rules(cls, raw: Dict[str, Any]) -> Tuple["Config", List[str]]:
        block = raw.get("asset_generation", {})
        if not isinstance(block, dict):
            return cls(), ["'asset_generation' must be an object"]
        c, problems = cls(), []

        def get(key, typ, check, msg):
            if key not in block:
                return
            v = block[key]
            if not isinstance(v, typ) or isinstance(v, bool) and typ is not bool or not check(v):
                problems.append(f"asset_generation.{key}: {msg}")
            else:
                setattr(c, key, v)

        get("provider", str, lambda v: v in ("ollama", "groq", "openai_compat"),
            "must be ollama, groq or openai_compat")
        get("model", str, bool, "must be a non-empty string")
        get("seed", int, lambda v: True, "must be an integer")
        get("max_retries", int, lambda v: 1 <= v <= 10, "must be 1..10")
        get("oracle", str, lambda v: v in ("none", "llm_consensus"), "must be \"none\" or \"llm_consensus\"")
        get("oracle_candidates", int, lambda v: 2 <= v <= len(llmgen.ORACLE_STYLES),
            f"must be 2..{len(llmgen.ORACLE_STYLES)}")
        get("min_examples_for_oracle", int, lambda v: v >= 1, "must be >= 1")
        get("max_case_families", int, lambda v: 1 <= v <= 20, "must be 1..20")
        get("known_solutions", int, lambda v: 0 <= v <= 5, "must be 0..5")
        get("max_input_bytes", int, lambda v: v > 0, "must be > 0")
        get("oracle_max_input_bytes", int, lambda v: v > 0, "must be > 0")
        get("description", str, lambda v: True, "must be a string")
        get("input_spec", dict, lambda v: True, "must be an object")
        ex = block.get("examples", [])
        if not isinstance(ex, list) or not all(isinstance(e, dict) and isinstance(e.get("input"), str)
                                               and isinstance(e.get("output"), str) for e in ex):
            problems.append("asset_generation.examples: must be a list of {\"input\": str, \"output\": str}")
        else:
            c.examples = [(e["input"], e["output"]) for e in ex]
        if raw.get("sample_output") is not None:
            if not isinstance(raw["sample_output"], str):
                problems.append("'sample_output' must be a string")
            elif isinstance(raw.get("sample_input"), str):
                c.examples.insert(0, (raw["sample_input"], raw["sample_output"]))
        return c, problems

    def public(self) -> Dict[str, Any]:
        d = {k: v for k, v in self.__dict__.items() if k not in ("description", "input_spec", "examples")}
        return d


@dataclass
class Preparation:
    overlay: Optional[AssetOverlay]
    missing: Dict[str, List[str]]
    bundle_key: Optional[str] = None
    cache_hit: bool = False
    bundle_dir: Optional[Path] = None


# -- 1. inventory -------------------------------------------------------------------
def _exists(base: Path, rel) -> bool:
    return isinstance(rel, str) and bool(rel) and (base / rel).exists()


def find_missing(raw: Dict[str, Any], base: Path) -> Dict[str, List[str]]:
    """Missing assets per metric (``"<rules>"`` for rules-level ones). Analyzers
    this module does not know (plugins) are left alone."""
    out: Dict[str, List[str]] = {}
    ref_named = raw.get("reference") is not None
    ref_ok = ref_named and _exists(base, raw["reference"])
    if ref_named and not ref_ok:
        out["<rules>"] = [f"reference solution {raw['reference']}"]
    for m in raw.get("metrics", []) if isinstance(raw.get("metrics"), list) else []:
        if not isinstance(m, dict) or not isinstance(m.get("params", {}), dict):
            continue
        name, analyzer, p = m.get("name"), m.get("analyzer"), m.get("params", {})
        miss: List[str] = []
        if analyzer == "io_tests":
            folder = base / p["testset_dir"] if isinstance(p.get("testset_dir"), str) else None
            tests = sorted(folder.glob("*.in")) if folder is not None and folder.is_dir() else []
            if folder is None or not folder.is_dir() or (not tests and not p.get("generated")):
                miss.append("test inputs")
            lacking = [t for t in tests if not t.with_suffix(".out").exists()]
            if lacking and not ref_ok:
                miss.append(f"expected outputs for {len(lacking)} test(s)")
            if p.get("generated"):
                if not ref_ok:
                    miss.append("a reference for generated tests")
                if not _exists(base, p.get("generator", "gen.py")):
                    miss.append("input generator")
        elif analyzer == "edge_case_runner":
            cf = p.get("cases_file", "edge_cases.json")
            if not _exists(base, cf):
                miss.append("corner cases")
            elif not ref_ok and not _all_expected(base / cf):
                miss.append("expected outputs for corner cases")
            if int(p.get("random_tests", 0) or 0) > 0:
                if not _exists(base, p.get("generator", "gen.py")):
                    miss.append("input generator")
                if not ref_ok:
                    miss.append("a reference for random tests")
        elif analyzer == "complexity_estimator":
            if not _exists(base, p.get("generator", "gen.py")):
                miss.append("input generator")
        elif analyzer == "sanitizer_run":
            if not _exists(base, p.get("cases_file", "edge_cases.json")):
                miss.append("extra inputs to replay (optional)")
        elif analyzer == "similarity_flag":
            for key in ("corpus_dir", "known_dir"):
                if p.get(key) and not (base / str(p[key])).is_dir():
                    miss.append(f"{key} {p[key]}")
        if miss:
            out[str(name)] = miss
    return out


def _all_expected(path: Path) -> bool:
    try:
        return all("expected" in p for ps in load_cases(path).values() for p in ps)
    except Exception:  # noqa: BLE001 - the rules check will report a broken file
        return False


def instructor_paths(raw: Dict[str, Any], base: Path) -> List[Path]:
    """Instructor files the generated assets depend on (cache invalidation)."""
    paths = []
    for rel in [raw.get("reference"), raw.get("statement"), "edge_cases.json", "gen.py"]:
        if _exists(base, rel):
            paths.append(base / rel)
    for m in raw.get("metrics", []):
        for v in (m.get("params", {}) or {}).values() if isinstance(m, dict) else []:
            if isinstance(v, str) and 0 < len(v) < 256 and _exists(base, v):
                paths.append(base / v)
    return paths


# -- entry point ----------------------------------------------------------------------
def prepare_assets(rules_path, llm: LLMClient, store: AssetStore, cache_root: Path) -> Preparation:
    path = Path(rules_path).resolve()
    try:
        text = path.read_text()
        raw = json.loads(text)
    except (OSError, ValueError):
        return Preparation(None, {})  # load_rules reports the problem properly
    if not isinstance(raw, dict):
        return Preparation(None, {})
    base = path.parent
    missing = find_missing(raw, base)
    if not missing:
        return Preparation(None, {})
    cfg, problems = Config.from_rules(raw)
    if cfg.input_spec is not None:
        problems += [f"asset_generation.input_spec: {p}" for p in check_spec(cfg.input_spec)]
    if problems:
        raise RulesError(path, problems)

    statement = ""
    if isinstance(raw.get("statement"), str) and _exists(base, raw["statement"]):
        statement = (base / raw["statement"]).read_text(errors="replace")
    if cfg.description:
        statement = (statement + "\n\n" + cfg.description).strip()

    deps = {
        "generator_version": GENERATOR_VERSION, "prompt_version": llmgen.PROMPT_VERSION,
        "spec_version": SPEC_VERSION, "rules_sha256": hashlib.sha256(text.encode()).hexdigest(),
        "statement_sha256": hashlib.sha256(statement.encode()).hexdigest(),
        "instructor_assets": hash_paths(instructor_paths(raw, base)),
        "settings": cfg.public(), "compiler": tools.version(_cc(raw)),
    }
    key = hashlib.sha256(json.dumps(deps, sort_keys=True).encode()).hexdigest()
    digest = llm.model_identity(cfg.provider, cfg.model)

    bundle = store.get_bundle(key)
    if bundle is not None and digest and bundle["model_digest"] and digest != bundle["model_digest"]:
        store.delete_bundle(key)  # same model name, different weights: regenerate
        bundle = None
    if bundle is not None and bundle["manifest"].get("transient_failures") and not llm.offline:
        bundle = None  # built while the model was unreachable: try again
    cache_hit = bundle is not None
    if bundle is None:
        builder = _Builder(raw, base, cfg, statement, missing, llm, digest)
        manifest, records = builder.build()
        store.put_bundle(key, problem=str(raw.get("problem", "unknown")), rules_sha256=deps["rules_sha256"],
                         dependencies=deps, provider=cfg.provider, model=cfg.model, model_digest=digest,
                         generator_version=GENERATOR_VERSION, manifest=manifest, assets=records,
                         events=builder.gen.events)
        bundle = store.get_bundle(key)
        assert bundle is not None
    manifest = bundle["manifest"]
    bundle_dir = Path(cache_root) / "assets" / key[:24]
    materialize(store.assets(key, "validated"), bundle_dir)
    overlay = overlay_from_manifest(manifest, bundle_dir, key, bundle["model_digest"])
    return Preparation(overlay, missing, key, cache_hit, bundle_dir)


def _cc(raw) -> str:
    comp = raw.get("compile", {})
    return comp.get("cc", "gcc") if isinstance(comp, dict) else "gcc"


# -- 3-5. generate, validate, decide ---------------------------------------------------
def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _family_name(name: str, i: int) -> str:
    clean = re.sub(r"[^a-z0-9_]+", "_", name.lower()).strip("_")[:40]
    return clean or f"family_{i}"


class _Builder:
    def __init__(self, raw, base: Path, cfg: Config, statement: str, missing, llm: LLMClient,
                 digest: Optional[str]):
        self.raw, self.base, self.cfg, self.statement, self.missing = raw, base, cfg, statement, missing
        self.gen = llmgen.Generator(llm, llmgen.Settings(cfg.provider, cfg.model, cfg.seed, cfg.max_retries,
                                                                  digest))
        self.records: List[AssetRecord] = []
        self.failures: List[Dict[str, str]] = []
        self.metrics_out: Dict[str, Dict[str, Any]] = {}
        self.instructor_inputs = ([raw["sample_input"]] if isinstance(raw.get("sample_input"), str) else []) + \
            [i for i, _ in cfg.examples if i != raw.get("sample_input")]
        self.metrics = [m for m in raw.get("metrics", []) if isinstance(m, dict)]
        self.ref_ok = raw.get("reference") is not None and _exists(base, raw["reference"])

    # -- helpers ------------------------------------------------------------------
    def add(self, kind, name, status, origin, detail="", content=None, path=None) -> AssetRecord:
        rec = AssetRecord(kind, name, status, origin, detail, content, path,
                          _sha(content) if content is not None else None)
        self.records.append(rec)
        return rec

    def fail(self, step: str, detail: str) -> None:
        self.failures.append({"step": step, "detail": detail})

    def _metrics(self, analyzer: str) -> List[Dict[str, Any]]:
        return [m for m in self.metrics if m.get("analyzer") == analyzer and str(m.get("name")) in self.missing]

    # -- build -----------------------------------------------------------------
    def build(self) -> Tuple[Dict[str, Any], List[AssetRecord]]:
        need_gen = any("input generator" in v for v in self.missing.values())
        need_inputs = any(m in self.missing for m in
                          [str(x.get("name")) for x in self.metrics
                           if x.get("analyzer") in ("io_tests", "edge_case_runner", "sanitizer_run")])
        self.spec = self._input_spec() if (need_gen or need_inputs) else None
        self.gen_rel = self._generator() if self.spec is not None else None
        self.pool = self._input_pool() if self.spec is not None else {}
        self.expected_kind, self.oracle_rel, self.oracle_out = self._oracle()
        self.known_rel = self._known() if any("known_dir" in " ".join(v) for v in self.missing.values()) else None

        overlay_params: Dict[str, Dict[str, Any]] = {}
        not_performed: Dict[str, str] = {}
        for m in self.metrics:
            name = str(m.get("name"))
            if name not in self.missing:
                continue
            decide = getattr(self, f"_decide_{m.get('analyzer')}", None)
            if decide is None:
                continue
            status, detail, over = decide(name, m.get("params", {}) or {})
            self.metrics_out[name] = {"analyzer": m.get("analyzer"), "status": status, "detail": detail,
                                      "missing": self.missing[name], "overrides": over}
            if status == "not_performed":
                not_performed[name] = detail
            elif over:
                overlay_params[name] = over

        reference = None
        replace_reference = False
        if self.oracle_rel:
            reference, replace_reference = self.oracle_rel, True
        elif "<rules>" in self.missing:
            replace_reference = True  # named but missing: grade without it
        manifest = {
            "expected_outputs_from": self.expected_kind,
            "metrics": self.metrics_out, "params": overlay_params, "not_performed": not_performed,
            "reference": reference, "replace_reference": replace_reference,
            "failures": self.failures, "missing": self.missing,
            # True when the LLM was unreachable: kept for the audit trail, but
            # regenerated on the next run that can reach the model
            "transient_failures": any(r.status == "unavailable" and "LLM unavailable" in r.detail
                                      for r in self.records),
            "counts": {"generated": sum(r.origin in ORIGIN_GENERATED and r.status in ("validated", "rejected")
                                        for r in self.records),
                       **{s: sum(r.status == s for r in self.records)
                          for s in ("validated", "rejected", "skipped", "unavailable")}},
        }
        return manifest, self.records

    # -- input spec + generator ------------------------------------------------------
    def _input_spec(self) -> Optional[InputSpec]:
        if self.cfg.input_spec is not None:
            spec, origin = self.cfg.input_spec, "instructor"
            problems = [f"instructor input {i} does not match: {e[0]}"
                        for i, s in enumerate(self.instructor_inputs, 1) for e in [InputSpec(spec).validate(s)] if e]
        elif not self.statement.strip():
            self.add("input_spec", "input_spec", "unavailable", "llm",
                     "no problem statement or asset_generation.description to derive the input format from")
            self.fail("input_spec", "no specification available")
            return None
        elif not self.instructor_inputs:
            self.add("input_spec", "input_spec", "unavailable", "llm",
                     "no instructor sample input to validate a derived input format against")
            self.fail("input_spec", "no instructor input to validate against")
            return None
        else:
            spec, origin = llmgen.propose_input_spec(self.gen, self.statement, self.instructor_inputs), "llm"
            problems = [] if spec is not None else [f"no valid input specification ({self.gen.last_error})"]
        if problems:
            status = self.gen.failed_status() if origin == "llm" else "rejected"
            self.add("input_spec", "input_spec", status, origin, "; ".join(problems),
                     json.dumps(spec, sort_keys=True) if spec is not None else None)
            self.fail("input_spec", "; ".join(problems))
            return None
        self.add("input_spec", "input_spec", "validated", origin,
                 f"accepts all {len(self.instructor_inputs)} instructor input(s)",
                 json.dumps(spec, indent=2, sort_keys=True), "input_spec.json")
        return InputSpec(spec)

    def _generator(self) -> Optional[str]:
        spec = self.spec
        assert spec is not None
        content = GEN_TEMPLATE.format(version=GENERATOR_VERSION, spec_json=json.dumps(spec.spec, sort_keys=True))
        sizes = sorted({s for s in [1, 2, 3, 5, 8, 13] if spec.supports_size(s)} | set(self._requested_sizes()))
        problems = []
        for size in sizes:
            if not spec.supports_size(size):
                continue  # reported per metric
            a = spec.generate(size, seeded_rng(self.cfg.seed, "check", size))
            b = spec.generate(size, seeded_rng(self.cfg.seed, "check", size))
            if a != b:
                problems.append(f"not deterministic at size {size}")
            err = spec.validate(a)
            if err:
                problems.append(f"size {size}: generated input breaks the spec: {err[0]}")
        if problems:
            self.add("generator", "gen.py", "rejected", "deterministic", "; ".join(problems), content)
            self.fail("generator", "; ".join(problems))
            return None
        self.add("generator", "gen.py", "validated", "deterministic",
                 f"deterministic and spec-valid at sizes {sizes}", content, "gen.py")
        return "gen.py"

    def _requested_sizes(self) -> List[int]:
        out = []
        for m in self.metrics:
            p = m.get("params", {}) or {}
            if m.get("analyzer") == "complexity_estimator":
                out += [s for s in p.get("sizes", []) if isinstance(s, int)]
            elif m.get("analyzer") == "edge_case_runner" and int(p.get("random_tests", 0) or 0) > 0:
                out += [s for s in p.get("sizes", DEFAULT_SIZES) if isinstance(s, int)]
            elif m.get("analyzer") == "io_tests":
                out += [g["size"] for g in p.get("generated", []) if isinstance(g, dict) and isinstance(g.get("size"), int)]
        return out

    def _sizes_ok(self, sizes) -> Optional[str]:
        bad = [s for s in sizes if self.spec is None or not self.spec.supports_size(s)]
        if bad:
            r = self.spec.size_range() if self.spec else None
            return f"requested size(s) {bad} are outside the input's allowed range {list(r) if r else '?'}"
        return None

    # -- input pool ----------------------------------------------------------------------
    def _input_pool(self) -> Dict[str, List[Tuple[str, str]]]:
        """family -> [(input, origin)], every input validated against the spec."""
        spec = self.spec
        assert spec is not None
        pool: Dict[str, List[Tuple[str, str]]] = {}
        seen = set(self.instructor_inputs)

        def offer(family: str, text: str, origin: str) -> None:
            label = f"{family}/{len(pool.get(family, [])) + 1}"
            if not isinstance(text, str):
                return
            text = text if text.endswith("\n") else text + "\n"
            errs = spec.validate(text)
            if not errs and len(text) > self.cfg.max_input_bytes:
                errs = [f"larger than {self.cfg.max_input_bytes} bytes"]
            if errs:
                self.add("test_input", label, "rejected", origin, errs[0], text[:2000])
                return
            if text in seen:
                return
            seen.add(text)
            pool.setdefault(family, []).append((text, origin))
            self.add("test_input", label, "validated", origin, "matches the input spec", text)

        for fam, texts in spec.boundary_cases(seeded_rng(self.cfg.seed, "boundary"), self.cfg.max_input_bytes).items():
            for t in texts:
                offer(fam, t, "deterministic")
        for i, size in enumerate(s for s in [1, 2, 3, 5, 8, 13, 20] if spec.supports_size(s)):
            offer("random_small", spec.generate(size, seeded_rng(self.cfg.seed, "pool", size, i)), "deterministic")

        wanted = None
        for m in self._metrics("edge_case_runner"):
            c = (m.get("params", {}) or {}).get("cases", "all")
            if isinstance(c, list) and not _exists(self.base, (m.get("params") or {}).get("cases_file", "edge_cases.json")):
                wanted = [str(x) for x in c]
        families = llmgen.propose_case_families(self.gen, self.statement, spec.spec, self.instructor_inputs,
                                                wanted, self.cfg.max_case_families)
        if families is None:
            self.add("test_input", "llm_case_families", self.gen.failed_status(), "llm", self.gen.last_error)
            self.fail("case_families", f"no valid corner-case answer ({self.gen.last_error}); "
                                       "using deterministic boundary cases only")
        else:
            for i, f in enumerate(families, 1):
                name = f["name"] if wanted and f["name"] in wanted else _family_name(f["name"], i)
                if name in ("random_small", "random_stress") or (name in pool and not wanted):
                    name = f"llm_{name}"
                for t in f["inputs"]:
                    offer(name, t, "llm")
        return pool

    # -- expected outputs --------------------------------------------------------------
    def _needs_expected(self) -> bool:
        return any(m.get("analyzer") in ("io_tests", "edge_case_runner") for m in
                   [x for x in self.metrics if str(x.get("name")) in self.missing])

    def _oracle(self) -> Tuple[str, Optional[str], Dict[str, str]]:
        if self.ref_ok:
            return "instructor_reference", None, {}
        if not self._needs_expected():
            return "not_needed", None, {}
        if self.cfg.oracle != "llm_consensus":
            self.add("oracle", "oracle", "unavailable", "llm_oracle",
                     "no instructor reference; the LLM oracle is off (asset_generation.oracle = \"none\")")
            return ("instructor_outputs" if self.cfg.examples else "none"), None, {}
        if not self.statement.strip():
            self.add("oracle", "oracle", "unavailable", "llm_oracle", "no problem statement")
            self.fail("oracle", "no problem statement to write an oracle from")
            return ("instructor_outputs" if self.cfg.examples else "none"), None, {}

        comp = self.raw.get("compile", {}) if isinstance(self.raw.get("compile"), dict) else {}
        from ..compiler import split_flags

        runner = CandidateRunner(_cc(self.raw), split_flags(comp.get("flags", "-O2 -std=c11")),
                                 split_flags(comp.get("ldflags", "-lm")),
                                 float(self.raw.get("time_limit_s", 1)), int(self.raw.get("memory_limit_mb", 256)))
        try:
            labels = ["brute_force", "efficient", "careful"][: self.cfg.oracle_candidates]
            codes = []
            for i, label in enumerate(labels):
                code = llmgen.propose_program(
                    self.gen, f"oracle:{label}", self.statement, self.instructor_inputs,
                    llmgen.ORACLE_STYLES[i], lambda c, lb=label: compile_problems(runner, c, f"check-{lb}"),
                    seed_offset=100 + i)
                if code is None:
                    self.add("oracle", label, self.gen.failed_status(), "llm_oracle",
                             f"no program that passes the static screen and compiles ({self.gen.last_error})")
                else:
                    codes.append((label, code))
            if not codes:
                self.fail("oracle", "no candidate oracle program could be generated")
                return ("instructor_outputs" if self.cfg.examples else "none"), None, {}
            validation = [t for fam in self.pool.values() for t, _ in fam if len(t) <= self.cfg.oracle_max_input_bytes]
            compare = next(((m.get("params") or {}).get("compare", "trim") for m in self.metrics
                            if m.get("analyzer") == "io_tests"), "trim")
            verdict = select_oracle(runner, codes, self.cfg.examples, validation, compare,
                                    self.cfg.min_examples_for_oracle)
        finally:
            runner.close()
        for c in verdict.candidates:
            ok = verdict.accepted is c
            self.add("oracle", c.label, "validated" if ok else "rejected", "llm_oracle",
                     verdict.reason if ok else "; ".join(c.problems) or verdict.reason, c.code,
                     "oracle/oracle.c" if ok else None)
        if verdict.accepted is None:
            self.fail("oracle", verdict.reason)
            return ("instructor_outputs" if self.cfg.examples else "none"), None, {}
        return "llm_consensus_oracle", "oracle/oracle.c", verdict.expected

    def _expected(self, text: str) -> Tuple[bool, Optional[str]]:
        """(can this input be checked, its stored expected output or None when
        the reference computes it at grade time)."""
        if self.expected_kind == "instructor_reference":
            return True, None
        if self.expected_kind == "llm_consensus_oracle" and text in self.oracle_out:
            return True, self.oracle_out[text]
        return False, None

    # -- known solutions --------------------------------------------------------------
    def _known(self) -> Optional[str]:
        if not self.statement.strip() or self.cfg.known_solutions == 0:
            self.add("known_solution", "known", "unavailable", "llm", "no problem statement")
            return None
        safe = re.sub(r"[^A-Za-z0-9.]+", "-", self.cfg.model)
        sources = {}
        for i in range(self.cfg.known_solutions):
            code = llmgen.propose_program(
                self.gen, f"known:{i + 1}", self.statement, self.instructor_inputs,
                llmgen.ORACLE_STYLES[i % len(llmgen.ORACLE_STYLES)],
                lambda c: [] if re.search(r"\bmain\s*\(", c) and len(c) < 50_000 else ["not a C program"],
                seed_offset=200 + i)
            name = f"llm_{safe}_{i + 1}.c"
            if code is None:
                self.add("known_solution", name, self.gen.failed_status(), "llm",
                         f"no usable program ({self.gen.last_error})")
                continue
            # compared as text only; never compiled or run
            self.add("known_solution", name, "validated", "llm", "text-only comparison corpus", code, f"known/{name}")
            sources[name] = f"LLM-generated ({self.cfg.model})"
        if not sources:
            self.fail("known_solutions", "no LLM solution could be generated")
            return None
        self.add("known_solution", "sources.json", "validated", "llm", "labels",
                 json.dumps(sources, indent=2, sort_keys=True) + "\n", "known/sources.json")
        return "known"

    # -- per-analyzer decisions: (status, detail, param overrides) -------------------------
    def _pool_items(self) -> List[Tuple[str, str, str]]:
        return [(fam, t, o) for fam, items in self.pool.items() for t, o in items]

    def _decide_io_tests(self, name, p):
        over: Dict[str, Any] = {}
        skipped: List[str] = []
        folder = self.base / p["testset_dir"] if isinstance(p.get("testset_dir"), str) else None
        tests = sorted(folder.glob("*.in")) if folder is not None and folder.is_dir() else []
        rel = f"tests_{_family_name(name, 0)}"
        files: List[Tuple[str, str, Optional[str], str]] = []  # (stem, input, output, origin)
        if tests:
            for t in tests:
                out = t.with_suffix(".out")
                if out.exists():
                    files.append((t.stem, t.read_text(), out.read_text(), "instructor"))
                elif self.expected_kind in ("instructor_reference", "llm_consensus_oracle"):
                    ok, exp = self._expected(t.read_text())
                    if ok:
                        files.append((t.stem, t.read_text(), exp, "instructor"))
                    else:
                        skipped.append(f"test {t.stem}: too large to cross-check the oracle")
                else:
                    skipped.append(f"test {t.stem}: no expected output and no trusted reference")
            materialize_needed = bool(skipped) or any(f[2] is not None and not (folder / f"{f[0]}.out").exists()
                                                      for f in files)
        else:
            for i, (inp, out) in enumerate(self.cfg.examples, 1):
                files.append((f"ex{i:02d}", inp, out, "instructor_example"))
            n = 0
            for fam, text, origin in self._pool_items():
                ok, exp = self._expected(text)
                if ok:
                    n += 1
                    files.append((f"g{n:03d}_{fam}"[:60], text, exp, origin))
                else:
                    skipped.append(f"{fam}: no trusted expected output")
            materialize_needed = True
        if materialize_needed and files:
            for stem, inp, out, origin in files:
                self.add("test_input", f"{name}/{stem}.in", "validated", origin, "", inp, f"{rel}/{stem}.in")
                if out is not None:
                    src = origin if origin.startswith("instructor") or self.expected_kind != "llm_consensus_oracle" \
                        else "llm_oracle"
                    self.add("test_output", f"{name}/{stem}.out", "validated", src, "", out, f"{rel}/{stem}.out")
            over["testset_dir"] = f"{ASSETS_PREFIX}/{rel}"

        gen_specs = p.get("generated", [])
        n_generated = len(gen_specs)
        if gen_specs:
            sizes = [g.get("size") for g in gen_specs if isinstance(g, dict)]
            if self.expected_kind not in ("instructor_reference", "llm_consensus_oracle"):
                over["generated"] = []
                skipped.append(f"{n_generated} generated hidden test(s): no trusted reference")
                n_generated = 0
            elif not _exists(self.base, p.get("generator", "gen.py")):
                why = self._sizes_ok(sizes) if self.gen_rel else "no validated input generator"
                if why:
                    over["generated"] = []
                    skipped.append(f"{n_generated} generated hidden test(s): {why}")
                    n_generated = 0
                else:
                    over["generator"] = f"{ASSETS_PREFIX}/{self.gen_rel}"
        for s in skipped:
            self.add("test_input", f"{name}: {s.split(':')[0]}", "skipped", "deterministic", s)
        performed = len(files) + n_generated
        if performed == 0:
            return "not_performed", self._why_no_expected("correctness tests"), {}
        detail = f"{len(files)} test(s)" + (f" + {n_generated} generated" if n_generated else "") + \
                 f"; expected outputs from {self.expected_kind.replace('_', ' ')}"
        if skipped:
            return "partial", detail + f"; {len(skipped)} skipped", over
        return "prepared", detail, over

    def _why_no_expected(self, what: str) -> str:
        outputs = ("the instructor's example outputs cover only the correctness examples"
                   if self.cfg.examples else "no instructor outputs")
        return (f"no trustworthy expected outputs for {what}: no instructor reference, {outputs}, and no "
                f"validated oracle. The submission's own output is never used as the answer key.")

    def _decide_edge_case_runner(self, name, p):
        over: Dict[str, Any] = {}
        skipped: List[str] = []
        cf_rel = p.get("cases_file", "edge_cases.json")
        wanted = p.get("cases", "all")
        rel = f"edge_cases_{_family_name(name, 0)}.json"
        fams: Dict[str, List[dict]] = {}
        if _exists(self.base, cf_rel):
            for fam, probes in load_cases(self.base / cf_rel).items():
                for probe in probes:
                    ok, exp = (True, probe["expected"]) if "expected" in probe else self._expected(probe["input"])
                    if ok:
                        fams.setdefault(fam, []).append({**probe, **({"expected": exp} if exp is not None else {})})
                    else:
                        skipped.append(f"{fam}: no trusted expected output")
            origin = "instructor"
        else:
            for fam, text, o in self._pool_items():
                if isinstance(wanted, list) and fam not in wanted:
                    continue
                ok, exp = self._expected(text)
                if ok:
                    fams.setdefault(fam, []).append({"input": text, **({"expected": exp} if exp is not None else {})})
                else:
                    skipped.append(f"{fam}: no trusted expected output")
            origin = "generated"
        if isinstance(wanted, list):
            missing_fams = [w for w in wanted if w not in fams]
            skipped += [f"{w}: family could not be generated or checked" for w in missing_fams]
            if missing_fams:
                over["cases"] = [w for w in wanted if w in fams]
        self.add("edge_cases", f"{name}/{rel}", "validated", origin,
                 f"{sum(len(v) for v in fams.values())} probe(s) in {len(fams)} family(ies)",
                 json.dumps(fams, indent=2), rel)
        over["cases_file"] = f"{ASSETS_PREFIX}/{rel}"

        n_random = int(p.get("random_tests", 0) or 0)
        if n_random > 0:
            if self.expected_kind not in ("instructor_reference", "llm_consensus_oracle"):
                over["random_tests"] = 0
                skipped.append(f"{n_random} random stress test(s): no trusted reference")
                n_random = 0
            elif not _exists(self.base, p.get("generator", "gen.py")):
                why = self._sizes_ok(p.get("sizes", DEFAULT_SIZES)) if self.gen_rel else "no validated input generator"
                if why:
                    over["random_tests"] = 0
                    skipped.append(f"{n_random} random stress test(s): {why}")
                    n_random = 0
                else:
                    over["generator"] = f"{ASSETS_PREFIX}/{self.gen_rel}"
        for s in skipped:
            self.add("test_input", f"{name}: {s.split(':')[0]}", "skipped", "deterministic", s)
        probes = sum(len(v) for v in fams.values())
        if probes + n_random == 0:
            self.records = [r for r in self.records if r.path != rel]
            return "not_performed", self._why_no_expected("corner cases"), {}
        detail = f"{probes} corner-case probe(s) in {len(fams)} family(ies)" + \
                 (f" + {n_random} random" if n_random else "") + \
                 f"; expected outputs from {self.expected_kind.replace('_', ' ')}"
        return ("partial" if skipped else "prepared"), detail + (f"; {len(skipped)} skipped" if skipped else ""), over

    def _decide_complexity_estimator(self, name, p):
        if _exists(self.base, p.get("generator", "gen.py")):
            return "ready", "instructor generator", {}
        if not self.gen_rel:
            return "not_performed", "no input generator: the input format could not be established", {}
        why = self._sizes_ok([s for s in p.get("sizes", []) if isinstance(s, int)])
        if why:
            return "not_performed", why, {}
        return "prepared", "generated input generator (validated spec, deterministic)", \
            {"generator": f"{ASSETS_PREFIX}/{self.gen_rel}"}

    def _decide_sanitizer_run(self, name, p):
        items = [t for _, t, _ in self._pool_items()] + [i for i in self.instructor_inputs]
        if not items:
            return "ready", "sample input and any test inputs only", {}
        rel = "replay_inputs.json"
        if not any(r.path == rel for r in self.records):
            self.add("inputs", rel, "validated", "deterministic" if self.pool else "instructor",
                     f"{len(items)} validated input(s)",
                     json.dumps({"generated_inputs": items}, indent=2), rel)
        return "prepared", f"{len(items)} validated input(s) to replay (instructor + generated)", \
            {"cases_file": f"{ASSETS_PREFIX}/{rel}"}

    def _decide_similarity_flag(self, name, p):
        over: Dict[str, Any] = {}
        notes = []
        for key in ("corpus_dir", "known_dir"):
            if p.get(key) and not (self.base / str(p[key])).is_dir():
                if key == "known_dir" and self.known_rel:
                    over[key] = f"{ASSETS_PREFIX}/{self.known_rel}"
                    notes.append("known solutions generated by the LLM")
                else:
                    over[key] = ""
                    notes.append(f"{key} {p[key]} not found and cannot be generated")
        remaining = [k for k in ("corpus_dir", "known_dir") if over.get(k, p.get(k))]
        if not remaining:
            return "not_performed", "; ".join(notes) + "; nothing to compare against", {}
        return ("partial" if any("cannot" in n for n in notes) else "prepared"), "; ".join(notes), over


# -- 6. materialise + overlay ----------------------------------------------------------
def _safe_path(root: Path, rel: str) -> Path:
    p = (root / rel).resolve()
    if rel.startswith("/") or ".." in Path(rel).parts or root.resolve() not in p.parents:
        raise ValueError(f"unsafe asset path {rel!r}")
    return p


def materialize(records: List[AssetRecord], bundle_dir: Path) -> None:
    """Write validated assets so the folder holds exactly them (an extra or
    edited file would silently change the test set, so the folder is rebuilt
    whenever it differs from the database)."""
    files = {r.path: r.content or "" for r in records if r.path}
    if bundle_dir.is_dir() and _dir_matches(bundle_dir, files):
        return
    bundle_dir.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=".tmp-", dir=str(bundle_dir.parent)))
    for rel, content in files.items():
        dst = _safe_path(tmp, rel)
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(content)
    shutil.rmtree(bundle_dir, ignore_errors=True)
    try:
        tmp.rename(bundle_dir)
    except OSError:  # a concurrent grader materialised the same bundle first
        shutil.rmtree(tmp, ignore_errors=True)


def _dir_matches(root: Path, files: Dict[str, str]) -> bool:
    on_disk = {f.relative_to(root).as_posix() for f in root.rglob("*") if f.is_file()}
    if on_disk != set(files):
        return False
    return all((root / rel).read_text() == content for rel, content in files.items())


def _abs(value, bundle_dir: Path):
    if isinstance(value, str) and value.startswith(ASSETS_PREFIX):
        rel = value[len(ASSETS_PREFIX):].lstrip("/")
        return str(_safe_path(bundle_dir, rel))
    return value


def overlay_from_manifest(manifest: Dict[str, Any], bundle_dir: Path, key: str,
                          model_digest: Optional[str]) -> AssetOverlay:
    params = {m: {k: _abs(v, bundle_dir) for k, v in over.items()} for m, over in manifest["params"].items()}
    reference = _safe_path(bundle_dir, manifest["reference"]) if manifest.get("reference") else None
    report = build_report_section(manifest, key, model_digest)
    return AssetOverlay(params=params, not_performed=dict(manifest["not_performed"]), reference=reference,
                        replace_reference=bool(manifest.get("replace_reference")), report=report)


def build_report_section(manifest: Dict[str, Any], key: str, model_digest: Optional[str]) -> Dict[str, Any]:
    """The ``asset_preparation`` part of the report. Only deterministic content
    (no timings, no cache-hit flag, no absolute paths), so the fingerprint is the
    same on every machine and on every re-run."""
    flags = []
    kind = manifest["expected_outputs_from"]
    if kind == "llm_consensus_oracle":
        flags.append({"type": "llm_oracle_used",
                      "detail": "Some expected outputs come from LLM-written programs that reproduced every "
                                "instructor example and agreed with each other on all validation inputs. "
                                "That is evidence, not proof: review before publishing."})
    for f in manifest["failures"]:
        flags.append({"type": "asset_generation_failed", "detail": f"{f['step']}: {f['detail']}"})
    partial = [n for n, m in manifest["metrics"].items() if m["status"] == "partial"]
    if partial:
        flags.append({"type": "tests_incomplete",
                      "detail": f"Parts of {', '.join(partial)} could not be prepared and were skipped "
                                f"(see asset_preparation); their scores cover only what actually ran."})
    return {
        "bundle_key": key, "generator_version": GENERATOR_VERSION, "model_digest": model_digest,
        "expected_outputs_from": kind,
        "assets": manifest.get("counts", {}),
        "metrics": {n: {k: v for k, v in m.items() if k != "overrides"} | {"overrides": sorted(m["overrides"])}
                    for n, m in manifest["metrics"].items()},
        "failures": manifest["failures"],
        "flags": flags,
    }
