"""originality: flag suspected copying from classmates, online sources or LLMs.

Method (the MOSS idea, "winnowing"):
1. Lex the code and erase names and literals, so renaming variables, changing
   constants, reformatting or rewriting comments changes nothing.
2. Hash every run of k tokens; keep the minimum hash in each sliding window of
   w hashes. These "fingerprints" are robust to local edits.
3. Similarity of two programs = Dice overlap of their fingerprint sets.

The corpus is the folder of other submissions, plus an optional ``known_dir`` of
solutions collected from the web and generated by LLMs for this problem -- the
practical way to detect "pasted from ChatGPT": generate a few LLM answers in
advance and see whether a submission is a near-copy of one.

Fingerprints also found in the instructor's reference solution are ignored
(``ignore_reference``), so the shape every correct answer must share does not
count as copying. Programs with too little distinctive code are not judged.

A flag is a request for human review, not a verdict.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Dict, List, Set, Tuple

from ..ctokens import normalized, tokenize
from .base import Analyzer, AnalyzerResult, register


def fingerprints(source: str, k: int = 5, window: int = 4) -> Dict[int, int]:
    """hash -> first source line where it occurs."""
    toks = normalized(tokenize(source))
    if len(toks) < k:
        return {}
    grams: List[Tuple[int, int]] = []
    for i in range(len(toks) - k + 1):
        text = " ".join(t.text for t in toks[i:i + k])
        # hashlib, not hash(): Python's hash() is salted per process and would
        # make the similarity -- and the grade -- change between runs.
        h = int.from_bytes(hashlib.md5(text.encode()).digest()[:8], "big")
        grams.append((h, toks[i].line))
    selected: Dict[int, int] = {}
    if len(grams) <= window:
        h, line = min(grams)
        return {h: line}
    for i in range(len(grams) - window + 1):
        win = grams[i:i + window]
        h, line = min(win, key=lambda g: g[0])
        if h not in selected:
            selected[h] = line
    return selected


def dice(a: Set[int], b: Set[int]) -> float:
    if not a or not b:
        return 0.0
    return 2 * len(a & b) / (len(a) + len(b))


def line_ranges(lines: List[int]) -> str:
    if not lines:
        return ""
    lines = sorted(set(lines))
    out, start, prev = [], lines[0], lines[0]
    for n in lines[1:]:
        if n == prev + 1:
            prev = n
            continue
        out.append(f"{start}-{prev}" if start != prev else str(start))
        start = prev = n
    out.append(f"{start}-{prev}" if start != prev else str(start))
    return ", ".join(out)


@register
class SimilarityFlag(Analyzer):
    name = "similarity_flag"
    description = "Winnowing fingerprint similarity vs. classmates and known web/LLM solutions"
    needs_execution = False

    def validate(self, params, rules):
        problems = []
        if not params.get("corpus_dir") and not params.get("known_dir"):
            problems.append("set 'corpus_dir' and/or 'known_dir'")
        for key in ("corpus_dir", "known_dir"):
            if params.get(key) and not rules.resolve(params[key]).is_dir():
                problems.append(f"{key} not found: {params[key]}")
        t = params.get("flag_threshold", 0.85)
        if not isinstance(t, (int, float)) or not 0 < t <= 1:
            problems.append("'flag_threshold' must be in (0, 1]")
        return problems

    def run(self, ctx, params):
        k, w = int(params.get("k", 5)), int(params.get("window", 4))
        threshold = float(params.get("flag_threshold", 0.85))
        min_fp = int(params.get("min_fingerprints", 8))

        ignore: Set[int] = set()
        if params.get("ignore_reference", True) and ctx.rules.reference:
            ignore |= set(fingerprints(ctx.rules.reference.read_text(errors="replace"), k, w))
        mine_lines = fingerprints(ctx.source, k, w)
        mine = set(mine_lines) - ignore

        labels: Dict[str, str] = {}
        candidates: List[Tuple[Path, str]] = []
        if params.get("corpus_dir"):
            for p in sorted(ctx.rules.resolve(params["corpus_dir"]).glob("*.c")):
                candidates.append((p, "submission"))
        if params.get("known_dir"):
            kd = ctx.rules.resolve(params["known_dir"])
            if (kd / "sources.json").exists():
                labels = json.loads((kd / "sources.json").read_text())
            for p in sorted(kd.glob("*.c")):
                candidates.append((p, "known"))

        me = ctx.submission.resolve()
        matches = []
        for path, kind in candidates:
            if path.resolve() == me:
                continue
            theirs = set(fingerprints(path.read_text(errors="replace"), k, w)) - ignore
            sim = dice(mine, theirs)
            shared = mine & theirs
            matches.append({
                "file": _rel(path, ctx.rules.base_dir), "kind": kind,
                "source": labels.get(path.name, "classmate" if kind == "submission" else "known solution"),
                "similarity": round(sim, 3),
                "shared_lines": line_ranges([mine_lines[h] for h in shared]),
            })
        matches.sort(key=lambda m: (-m["similarity"], m["file"]))
        top = matches[: int(params.get("max_shown", 3))]
        best = top[0] if top else None
        evidence = {"method": f"winnowing k={k} w={w}, Dice overlap", "threshold": threshold,
                    "fingerprints": len(mine), "ignored_reference_fingerprints": len(ignore),
                    "compared_against": len(matches), "top_matches": top,
                    "max_similarity": best["similarity"] if best else 0.0}

        if len(mine) < min_fp:
            evidence["note"] = "too little distinctive code to judge originality"
            closest = (f" Closest: {best['file']} ({best['similarity']:.2f})." if best else "")
            return AnalyzerResult(score=1.0, evidence=evidence,
                                  feedback=f"Not judged: only {len(mine)} distinctive fingerprints "
                                           f"(minimum {min_fp}); the code is almost all the shape every "
                                           f"solution shares.{closest}")
        if not best or best["similarity"] < threshold:
            sim = best["similarity"] if best else 0.0
            return AnalyzerResult(score=1.0, evidence=evidence,
                                  feedback=f"Max similarity {sim:.2f} (threshold {threshold:.2f}); not flagged.")

        flagged = [m for m in matches if m["similarity"] >= threshold]
        flags = []
        for m in flagged:
            known = m["kind"] == "known"
            flags.append({
                "type": "suspected_external_copy" if known else "suspected_plagiarism",
                "detail": (f"{m['similarity']:.2f} similar to {m['file']} ({m['source']}); "
                           f"shared lines {m['shared_lines']}. Needs human review."),
                "similarity": m["similarity"], "match": m["file"],
            })
        score = 1.0 if params.get("flag_only", False) else 0.0
        what = ", ".join(f"{m['file']} ({m['source']}, {m['similarity']:.2f})" for m in flagged[:3])
        return AnalyzerResult(
            score=score, evidence=evidence, flags=flags,
            feedback=f"FLAGGED for review: highly similar to {what}.",
            suggestions=["This code closely matches another submission or a known source and will be "
                         "reviewed by the instructor. If you worked with someone or used a source, say so."],
        )


def _rel(path: Path, base: Path) -> str:
    try:
        return path.resolve().relative_to(base.resolve()).as_posix()
    except ValueError:
        return path.name
